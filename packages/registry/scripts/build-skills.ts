import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { manifest } from "../registry";
import { componentDocs } from "../../../apps/www/lib/component-docs";
import { groups, titles } from "../../../apps/www/lib/site";

/**
 * Writes skills/expressive/references/components.md, the per-component API
 * reference AI agents read, from the same data as the docs site. Run with the
 * site's tsconfig so its path aliases resolve:
 *   tsx --tsconfig ../../apps/www/tsconfig.json scripts/build-skills.ts
 */

const root = fileURLToPath(new URL("../../..", import.meta.url));
const out = join(root, "skills/expressive/references/components.md");

const components = manifest.filter((item) => item.type === "component" && !item.internal);
const groupOf = (name: string) => groups.find((group) => group.items.includes(name))?.title ?? "Other";
const cell = (text: string) => text.replaceAll("|", "\\|").replaceAll("\n", " ");

const lines: string[] = [
  "# Expressive components: API reference",
  "",
  "<!-- Generated by packages/registry/scripts/build-skills.ts from the docs site's data. Don't edit by hand. -->",
  "",
  `All ${components.length} components, grouped as on the docs site. Each section has the install command, what the`,
  "component is for, a usage example, its props, accessibility behavior and gotchas. Import paths assume the default",
  "`expressive.json` aliases (`@/components/expressive/*`, `@/lib/expressive/*`); check the project's own aliases.",
  "",
  "## Index",
  "",
];

for (const group of groups) {
  const names = group.items.filter((name) => components.some((item) => item.name === name));
  lines.push(`- **${group.title}**: ${names.map((name) => `[${titles[name] ?? name}](#${name})`).join(", ")}`);
}
lines.push("");

for (const group of groups) {
  for (const name of group.items) {
    const item = components.find((component) => component.name === name);
    const doc = componentDocs[name];
    if (!item || !doc) continue;
    const npm = (item.dependencies ?? []).map((dep) => dep.replace(/(?<=.)@[^@]*$/, ""));
    lines.push(
      `<a id="${name}"></a>`,
      "",
      `## ${titles[name] ?? name}`,
      "",
      `${item.description}`,
      "",
      `- Install: \`npx @grenishrai/expressive add ${name}\``,
      `- Group: ${groupOf(name)}`,
      `- Files: ${item.files.map((file) => `\`${file.path}\``).join(", ")}`,
      `- Expressive dependencies: ${item.registryDependencies?.length ? item.registryDependencies.map((dep) => `\`${dep}\``).join(", ") : "none"}`,
      `- npm dependencies: ${npm.length ? npm.map((dep) => `\`${dep}\``).join(", ") : "none"}`,
      `- Docs: https://expressive.grenishrai.pro/docs/components/${name}`,
      "",
      doc.overview,
      "",
      "### Usage",
      "",
      "```tsx",
      doc.usage,
      "```",
      "",
    );
    for (const guide of doc.guides ?? []) {
      lines.push(`### ${guide.title}`, "", ...guide.intro.flatMap((line) => [line, ""]), "```tsx", guide.code.trim(), "```", "");
      if (guide.tips) lines.push(...guide.tips.map((tip) => `- ${tip}`), "");
    }
    lines.push("### Props", "");
    for (const [part, rows] of Object.entries(doc.props)) {
      lines.push(`**${part}**`, "", "| Prop | Type | Default | Description |", "| --- | --- | --- | --- |");
      for (const row of rows) {
        lines.push(`| \`${cell(row.name)}\` | ${row.type ? `\`${cell(row.type)}\`` : ""} | ${row.default ? `\`${cell(row.default)}\`` : ""} | ${cell(row.description)} |`);
      }
      lines.push("");
    }
    lines.push("### Accessibility", "", ...doc.accessibility.map((line) => `- ${line}`), "");
    if (doc.notes?.length) lines.push("### Notes", "", ...doc.notes.map((line) => `- ${line}`), "");
  }
}

writeFileSync(out, `${lines.join("\n").trimEnd()}\n`);
console.log(`skills: ${components.length} components → ${out}`);
